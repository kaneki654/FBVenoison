"""Publish a new FBPoison build to the Vercel update service.

    python release.py --notes "fix: 2-cell action row"     bump patch + deploy
    python release.py --version 2.1.0 --notes "..."        explicit version
    python release.py --notes "..." --exe                  ship the binary too
    python release.py --set-token                          rotate the shared secret

What it does, in order: bundles the payload into api/_release.js, bumps
version.py, deploys with the Vercel CLI, then writes the live deployment URL
back into updater.py so the next build of the app knows where to phone home.
"""

import argparse
import base64
import datetime
import hashlib
import json
import os
import re
import secrets
import subprocess

from updater import POLL_SECONDS

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(HERE, "update_site")
CONFIG = os.path.join(HERE, "update_config.json")

# core.py is the whole point: it is the only module that can be swapped into a
# live process. The rest ride along and take effect on the next launch.
HOT_PAYLOAD = ["core.py"]
# Nothing else is worth shipping: a staged gui.py cannot be grafted onto a live
# window and a frozen build would never import it anyway. Ship the binary with
# --exe when the GUI itself changes.
COLD_PAYLOAD = []


def load_config():
    if os.path.exists(CONFIG):
        with open(CONFIG, encoding="utf-8") as fh:
            return json.load(fh)
    return {}


def save_config(cfg):
    with open(CONFIG, "w", encoding="utf-8") as fh:
        json.dump(cfg, fh, indent=2)


def current_version():
    with open(os.path.join(HERE, "version.py"), encoding="utf-8") as fh:
        m = re.search(r'APP_VERSION\s*=\s*"([^"]+)"', fh.read())
    return m.group(1) if m else "0.0.0"


def bump(v):
    parts = [int(x) if x.isdigit() else 0 for x in v.split(".")]
    while len(parts) < 3:
        parts.append(0)
    parts[-1] += 1
    return ".".join(str(p) for p in parts)


def write_version(v):
    path = os.path.join(HERE, "version.py")
    with open(path, encoding="utf-8") as fh:
        src = fh.read()
    src = re.sub(r'APP_VERSION\s*=\s*"[^"]+"', 'APP_VERSION = "%s"' % v, src)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(src)


def build_payload(include_exe):
    names = list(HOT_PAYLOAD) + list(COLD_PAYLOAD)
    if include_exe:
        names.append(os.path.join("dist", "fbpoison.exe"))
    files = {}
    for rel in names:
        path = os.path.join(HERE, rel)
        if not os.path.exists(path):
            print("  skip  %s (not found)" % rel)
            continue
        with open(path, "rb") as fh:
            blob = fh.read()
        key = os.path.basename(rel)
        files[key] = {
            "sha256": hashlib.sha256(blob).hexdigest(),
            "size": len(blob),
            "b64": base64.b64encode(blob).decode("ascii"),
        }
        print("  add   %-16s %8d bytes  %s"
              % (key, len(blob), files[key]["sha256"][:16]))
    return files


def write_release_js(version, notes, files):
    out = os.path.join(SITE, "api", "_release.js")
    payload = {
        "version": version,
        "notes": notes,
        "published": datetime.datetime.now(datetime.timezone.utc)
                              .isoformat(timespec="seconds"),
        "files": files,
    }
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("// Generated by release.py - do not edit by hand.\n")
        fh.write("module.exports = ")
        json.dump(payload, fh, separators=(",", ":"))
        fh.write(";\n")
    return out


def run(cmd, cwd=None, stdin_text=None):
    print("  $ %s" % cmd)
    return subprocess.run(cmd, cwd=cwd, shell=True, text=True,
                          input=stdin_text, capture_output=True)


def deploy():
    res = run("vercel --prod --yes", cwd=SITE)
    out = (res.stdout or "") + (res.stderr or "")
    print(out.strip()[-1500:])
    if res.returncode != 0:
        raise SystemExit("vercel deploy failed (exit %d)" % res.returncode)
    urls = re.findall(r"https://[a-zA-Z0-9._-]+\.vercel\.app", out)
    # The last "Production:" URL is the stable alias; fall back to any match.
    prod = re.search(r"Production:\s*(https://\S+)", out)
    return (prod.group(1) if prod else (urls[-1] if urls else "")).strip()


def patch_updater(base_url, token):
    """Bake the endpoint into updater.py so a frozen build knows where to look."""
    path = os.path.join(HERE, "updater.py")
    with open(path, encoding="utf-8") as fh:
        src = fh.read()
    src = re.sub(
        r'UPDATE_BASE = os\.environ\.get\("FBPOISON_UPDATE_URL", "[^"]*"\)',
        'UPDATE_BASE = os.environ.get("FBPOISON_UPDATE_URL", "%s")' % base_url,
        src)
    src = re.sub(
        r'UPDATE_TOKEN = os\.environ\.get\("FBPOISON_UPDATE_TOKEN", "[^"]*"\)',
        'UPDATE_TOKEN = os.environ.get("FBPOISON_UPDATE_TOKEN", "%s")' % token,
        src)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(src)


def set_token(cfg):
    token = secrets.token_urlsafe(24)
    for env in ("production", "preview", "development"):
        run("vercel env rm UPDATE_TOKEN %s --yes" % env, cwd=SITE)
        res = run("vercel env add UPDATE_TOKEN %s" % env, cwd=SITE,
                  stdin_text=token + "\n")
        if res.returncode != 0:
            print("  ! could not set UPDATE_TOKEN for %s: %s"
                  % (env, (res.stderr or "").strip()[:200]))
    cfg["token"] = token
    save_config(cfg)
    print("  token set (%s…)" % token[:8])
    return token


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--notes", default="", help="one-line changelog")
    ap.add_argument("--version", default=None, help="explicit version")
    ap.add_argument("--exe", action="store_true", help="include dist/fbpoison.exe")
    ap.add_argument("--set-token", action="store_true",
                    help="generate and install a new shared secret")
    ap.add_argument("--no-deploy", action="store_true",
                    help="build the payload but skip the Vercel push")
    args = ap.parse_args()

    cfg = load_config()
    version = args.version or bump(current_version())
    notes = args.notes or "maintenance build"

    print("FBPoison release %s -> %s" % (current_version(), version))
    write_version(version)                # bump first, so the payload carries it
    files = build_payload(args.exe)
    if not files:
        raise SystemExit("nothing to publish")
    write_release_js(version, notes, files)

    if args.no_deploy:
        print("built api/_release.js (deploy skipped)")
        return

    url = cfg.get("url", "")
    new_url = deploy()
    if new_url:
        url = new_url
    if not url:
        raise SystemExit("could not determine the deployment URL - "
                         "pass it once with: vercel --prod, then rerun")

    if args.set_token or not cfg.get("token"):
        token = set_token(cfg)
        deploy()                          # re-deploy so the new env var is live
    else:
        token = cfg["token"]

    cfg["url"] = url
    cfg["version"] = version
    save_config(cfg)
    patch_updater(url, token)

    print()
    print("published %s" % version)
    print("  dashboard  %s" % url)
    print("  manifest   %s/api/manifest" % url)
    print("  clients pick it up within %d minutes" % (POLL_SECONDS // 60))


if __name__ == "__main__":
    main()
